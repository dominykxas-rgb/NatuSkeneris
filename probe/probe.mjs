import createVerovioModule from "verovio/wasm";
import { VerovioToolkit } from "verovio/esm";
import fs from "node:fs";
const VerovioModule = await createVerovioModule();
const tk = new VerovioToolkit(VerovioModule);
console.log("verovio", tk.getVersion());
const xml = fs.readFileSync("probe/probe.xml", "utf8");
tk.setOptions({ pageWidth: 2100, pageHeight: 2970, scale: 40, adjustPageHeight: true, header: "auto", footer: "none" });
console.log("load", tk.loadData(xml));
const svg = tk.renderToSVG(1);
const ids = [...svg.matchAll(/<g id="([^"]+)" class="(note|rest|chord|mRest|measure)"/g)].map((m) => `${m[2]}:${m[1]}`);
console.log("SVG", ids.join("  "));
console.log("title in svg:", svg.includes("Bandymas"));
console.log("pkIds kept:", ids.filter((x) => x.includes("pk")).length, "measure ids kept:", ids.filter((x) => /:m\d/.test(x)).length);
const mei = tk.getMEI();
console.log("MEI notes:", [...mei.matchAll(/<(note|rest|mRest)[^>]*xml:id="([^"]+)"/g)].map((m) => m[1] + ":" + m[2]).join(" "));
console.log("toolkit methods:", Object.getOwnPropertyNames(Object.getPrototypeOf(tk)).join(","));
fs.writeFileSync("probe/out.svg", svg);
